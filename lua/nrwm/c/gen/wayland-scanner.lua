if not vim then error('needs to be run with neovim') end
if not pcall(vim.treesitter.language.inspect,'xml') then error('treesitter-xml parser not found') end

local xml=dofile'gen/xml.lua'

local M={}

local function parse(source)
  ---@type table<string,fun(node: nrwm.xml.elem):any>
  local tbl
  local function pop1cif(node,ctag)
    if node.children[1] and node.children[1].tag==ctag then
      return tbl[ctag](table.remove(node.children,1))
    end
  end
  local function formatchc(node,ctags,out,minonce)
    assert(not minonce or #node.children>0)
    for _,i in ipairs(ctags) do
      out[i]={}
    end
    for _,cnode in ipairs(node.children) do
      assert(vim.tbl_contains(ctags,cnode.tag))
      table.insert(out[cnode.tag],tbl[cnode.tag](cnode))
    end
  end
  local function aemtpyc(node)
    assert(#node.children==0)
  end
  local function tonat(str)
    local n=tonumber(str)
    assert(not n or 1<=n)
    return n
  end
  local function aname(str)
    assert(str and str:find('^[a-zA-Z_][a-zA-Z0-9_]*$'))
    return str
  end
  tbl={
    protocol=function(node)
      local out={}
      out.name=aname(node.attr.name)
      out.copyright=pop1cif(node,'copyright')
      out.description=pop1cif(node,'description')
      formatchc(node,{'interface'},out,true)
      return out
    end,
    copyright=function(node)
      aemtpyc(node)
      return node.content
    end,
    description=function(node)
      aemtpyc(node)
      return {content=node.content,summary=node.attr.summary}
    end,
    interface=function(node)
      local out={}
      out.name=aname(node.attr.name)

      --- Doesn't check that children have specific version
      out.version=assert(tonat(assert(node.attr.version)))

      out.forzen=node.attr.frozen=='true'
      assert(not out.frozen or out.version==1)
      out.description=pop1cif(node,'description')
      formatchc(node,{'request','event','enum'},out,true)
      return out
    end,
    request=function(node)
      local out={}
      out.name=aname(node.attr.name)
      out.destructor=node.attr.type=='destructor'
      out.since=tonat(node.attr.since) or 1
      out.deprecated_since=tonat(node.attr['deprecated-since'])
      assert(not out.deprecated_since or out.deprecated_since>out.sice)
      out.description=pop1cif(node,'description')
      formatchc(node,{'arg'},out)
      return out
    end,
    event='later set',
    arg=function(node)
      local out={}
      out.name=aname(node.attr.name)
      out.type=assert(node.attr.type)
      assert(vim.tbl_contains({
        'int',
        'uint',
        'fixed',
        'string',
        'array',
        'fd',
        'new_id',
        'object',
      },out.type))
      out.summary=node.attr.summary
      out.allow_null=node.attr['allow-null']=='true'
      assert(not out.allow_null or out.type=='string' or out.type=='object')

      --- Doesn't check that these are exisisting enums/interfaces
      out.interface=node.attr.interface
      assert(not out.interface or out.type=='object' or out.type=='new_id')
      out.enum=node.attr.enum
      assert(not out.enum or out.type=='int' or out.type=='uint')

      out.description=pop1cif(node,'description')
      aemtpyc(node)
      return out
    end,
    enum=function(node)
      local out={}
      out.name=aname(node.attr.name)
      out.since=tonat(node.attr.since) or 1
      out.bitfield=node.attr.bitfield=='true'
      out.description=pop1cif(node,'description')
      formatchc(node,{'entry'},out)
      return out
    end,
    entry=function(node)
      local out={}
      out.name=aname(node.attr.name)
      out.value=assert(tonumber(assert(node.attr.value)))
      out.summary=node.attr.summary
      out.since=tonat(node.attr.since) or 1
      out.deprecated_since=tonat(node.attr['deprecated-since'])
      assert(not out.deprecated_since or out.deprecated_since>out.sice)
      out.description=pop1cif(node,'description')
      aemtpyc(node)
      return out
    end,
  }
  tbl.event=tbl.request
  local node=xml.parse(source)
  if node.tag~='protocol' then
    error''
  end
  return tbl.protocol(node)
end

local function generate(source)
  local protocol=parse(source)
  local out=vim.split([=[
--[[
DO NOT EDIT
This file is autogenerated from wayland-scanner.lua
To regenerate this file, run `nvim -l gen/wayland-scanner.lua`
--]]
]=],'\n')
  table.insert(out,'local ffi=require"ffi"')
  table.insert(out,'local wayland=require"nrwm.c.wayland"')
  table.insert(out,'local M={}')
  for _,i in ipairs(protocol.interface) do
    if #i.event>0 then
      table.insert(out,'ffi.cdef[=[')
      table.insert(out,('struct %s_listener {'):format(i.name))
      for _,event in ipairs(i.event) do
        table.insert(out,('void (*%s)('):format(event.name))
        table.insert(out,'void *data,')
        table.insert(out,('struct %s *%s'):format(i.name,i.name))
        for _,a in ipairs(event.arg) do
          table.insert(out,(',%s %s'):format(({
            int='int32_t',
            fd='int32_t',
            new_id=a.interface and ('struct %s*'):format(a.interface),
            uint='uint32_t',
            fixed='wl_fixed_t',
            string='const char*',
            object=a.interface and ('struct %s*'):format(a.interface) or 'void*',
            array='struct wl_array*',
          })[a.type],a.name))
        end
        table.insert(out,');')
      end
      table.insert(out,'};')
      table.insert(out,']=]')
    end
    table.insert(out,('M.%s={'):format(i.name))
    if #i.event>0 then
      table.insert(out,('add_listener=function(%s,listener,data)'):format(i.name))
      table.insert(out,'return wayland.wl_proxy_add_listener(')
      table.insert(out,('ffi.cast("struct wl_proxy *", %s),'):format(i.name))
      table.insert(out,'ffi.cast("void (**)(void)", listener), data)')
      table.insert(out,'end,')
    end
    for _,enum in ipairs(i.enum) do
      table.insert(out,('%s={'):format(enum.name))
      for _,e in ipairs(enum.entry) do
        table.insert(out,('%s = %d,')
        :format(e.name,e.value))
      end
      table.insert(out,'},')
    end
    table.insert(out,('set_user_data=function(%s,user_data)'):format(i.name))
    table.insert(out,'wayland.wl_proxy_set_user_data(')
    table.insert(out,('ffi.cast("struct wl_proxy *", %s), user_data)'):format(i.name))
    table.insert(out,'end,')
    table.insert(out,('get_user_data=function(%s)'):format(i.name))
    table.insert(out,'return wayland.wl_proxy_get_user_data(')
    table.insert(out,('ffi.cast("struct wl_proxy *", %s))'):format(i.name))
    table.insert(out,'end,')
    table.insert(out,('get_version=function(%s)'):format(i.name))
    table.insert(out,'return wayland.wl_proxy_get_version(')
    table.insert(out,('ffi.cast("struct wl_proxy *", %s))'):format(i.name))
    table.insert(out,'end,')
    local has_destroy
    for _,r in ipairs(i.request) do
      if r.destructor then
        has_destroy=true
      end
    end
    if not has_destroy and i.name~='wl_display' then
      table.insert(out,('destroy=function(%s)'):format(i.name))
      table.insert(out,'return wayland.wl_proxy_destroy(')
      table.insert(out,('ffi.cast("struct wl_proxy *", %s))'):format(i.name))
      table.insert(out,'end,')
    end
    for r_id_plus_1,r in ipairs(i.request) do
      local ret
      for _,a in ipairs(r.arg) do
        if a.type=='new_id' then
          ret=a
        end
      end
      table.insert(out,('%s=function(%s'):format(r.name,i.name))
      for _,a in ipairs(r.arg) do
        if a.type=='new_id' and not a.interface then
          table.insert(out,',interface,version')
        elseif a.type=='new_id' then
        else
          table.insert(out,(',%s'):format(a.name))
        end
      end
      table.insert(out,')')
      if ret and not ret.interface then
        table.insert(out,'return ffi.cast("void*",')
      elseif ret then
        table.insert(out,('return ffi.cast("struct %s *",'):format(ret.interface))
      end
      table.insert(out,'wayland.wl_proxy_marshal_flags(')
      table.insert(out,('ffi.cast("struct wl_proxy *", %s)'):format(i.name))
      table.insert(out,(',%d'):format(r_id_plus_1-1))
      if ret then
        if ret.interface then
          table.insert(out,(',M.%s.interface'):format(ret.interface))
        else
          table.insert(out,',interface')
        end
      else
        table.insert(out,',nil')
      end
      if ret and not ret.interface then
        table.insert(out,', version')
      else
        table.insert(out,(', wl_proxy_get_version(ffi.cast("struct wl_proxy *", %s))')
        :format(i.name))
      end
      if r.destructor then
        table.insert(out,', wayland.WL_MARSHAL_FLAG_DESTROY')
      else
        table.insert(out,', 0')
      end
      for _,a in ipairs(r.arg) do
        if a.type=='NEW_ID' then
          if not a.interface then
            table.insert(out,', interface->name, version')
          end
          table.insert(out,', nil')
        else
          table.insert(out,(', %s'):format(a.name))
        end
      end
      table.insert(out,')')
      if ret then
        table.insert(out,')')
      end
      table.insert(out,'end,')
    end
    table.insert(out,'interface=ffi.new("struct wl_interface[1]")')
    table.insert(out,'}')
    table.insert(out,('M.interface_ptr=ffi.cast("struct wl_interface*",M.%s.interface)')
    :format(i.name))
  end
  local interfaces={}
  for _, i in ipairs(protocol.interface) do
    interfaces[i.name]=true
  end
  local longets_null=0
  local arg_types={}
  local external={}
  for _, i in ipairs(protocol.interface) do
    arg_types[i.name]={}
    for m in coroutine.wrap(function()
      for _,e in ipairs(i.event) do
        coroutine.yield(e)
      end
      for _,r in ipairs(i.request) do
        coroutine.yield(r)
      end
    end) do
      local all_null=true
      local len=0
      local types={}
      for k,a in ipairs(m.arg) do
        len=len+1
        if a.type=='new_id' and not a.interface then
          len=len+2
        end
        if (a.type=='new_id' or a.type=='object') and a.interface then
          all_null=false
          types[len]=a.interface
        end
      end
      if all_null then
        longets_null=math.max(longets_null,len)
        arg_types[i.name][m.name]=true
      else
        arg_types[i.name][m.name]={types,len}
        for idx=1,len do
          if not types[idx] or interfaces[types[idx]] then
          else
            external[types[idx]]=true
          end
        end
      end
    end
  end
  if next(external) then
    table.insert(out,'local function ptr_reference_hack(val)')
    table.insert(out,'local hex=assert(tostring(val):match("0x(%x*)$"))')
    table.insert(out,'local n=ffi.new("intptr_t",tonumber(hex:sub(1,-9),16))')
    table.insert(out,'n=bit.lshift(n,32)+tonumber(hex:sub(-8),16)')
    table.insert(out,'return ffi.cast("struct wl_interface*",n)')
    table.insert(out,'end')
    table.insert(out,'ffi.cdef[[')
    for e in pairs(external) do
      table.insert(out,('extern const struct wl_interface %s_interface;'):format(e))
    end
    table.insert(out,']]')
    table.insert(out,'local external={')
    for e in pairs(external) do
      table.insert(out,('%s=ptr_reference_hack(wayland.%s_interface),'):format(e,e))
    end
    table.insert(out,'}')
  end
  for iname,arg_types2 in pairs(arg_types) do
    for mname,arg_type in pairs(arg_types2) do
      if arg_type~=true then
        local types,len=unpack(arg_type)
        table.insert(out,('local args_types_%s_%s=ffi.new("const struct wl_interface*[%d]",{')
        :format(iname,mname,len))
        for idx=1,len do
          if not types[idx] then
            table.insert(out,'nil,')
          elseif interfaces[types[idx]] then
            table.insert(out,('M.%s.interface_ptr,'):format(types[idx]))
          else
            table.insert(out,('external.%s,'):format(types[idx]))
            external[types[idx]]=true
          end
        end
        table.insert(out,'})')
      end
    end
  end
  table.insert(out,('local args_types_nil=ffi.new("const struct wl_interface*[%d]",{')
  :format(longets_null))
  for _=1,longets_null do
    table.insert(out,'nil,')
  end
  table.insert(out,'})')
  for _,i in ipairs(protocol.interface) do
    for m in coroutine.wrap(function()
      if #i.request>0 then
        table.insert(out,('local %s_requests=ffi.new("struct wl_message[%d]",{')
        :format(i.name,#i.request))
        for _,r in ipairs(i.request) do
          coroutine.yield(r)
        end
        table.insert(out,'})')
      end
      if #i.event>0 then
        table.insert(out,('local %s_events=ffi.new("struct wl_message[%d]",{')
        :format(i.name,#i.event))
        for _,e in ipairs(i.event) do
          coroutine.yield(e)
        end
        table.insert(out,'})')
      end
    end) do
      table.insert(out,('{%q,'):format(m.name))
      local sign=''
      if m.since>1 then
        sign=sign..m.since
      end
      for _,a in ipairs(m.arg) do
        if a.allow_null then
          sign=sign..'?'
        end
        sign=sign..({
            int='i',
            fd='h',
            new_id=a.interface and 'n' or 'sun',
            uint='u',
            fixed='f',
            string='s',
            object='o',
            array='a',
          })[a.type]
      end
      table.insert(out,('%q,'):format(sign))
      if arg_types[i.name][m.name]==true then
        table.insert(out,'args_types_nil')
      else
        table.insert(out,('args_types_%s_%s'):format(i.name,m.name))
      end
      table.insert(out,'},')
    end
    table.insert(out,('M.%s.interface[0].name=%s'):format(i.name,i.name))
    table.insert(out,('M.%s.interface[0].version=%s'):format(i.name,i.version))
    table.insert(out,('M.%s.interface[0].method_count=%d'):format(i.name,#i.request))
    table.insert(out,('M.%s.interface[0].methods=%s')
    :format(i.name,#i.request>0 and i.name..'_requests' or 'nil'))
    table.insert(out,('M.%s.interface[0].event_count=%d'):format(i.name,#i.event))
    table.insert(out,('M.%s.interface[0].events=%s')
    :format(i.name,#i.request>0 and i.name..'_events' or 'nil'))
  end
  table.insert(out,'return M')

  return out
end

function gen_protocol(protocol)
  local source=vim.fn.readblob('./gen/protocol/'..protocol..'.xml')
  local out=generate(source)
  vim.fn.writefile(out,protocol..'.lua')
end

gen_protocol('river-window-management-v1')

return M
